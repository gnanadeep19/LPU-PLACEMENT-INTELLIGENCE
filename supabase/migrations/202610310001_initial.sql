-- Foundation for a staged migration. Do not point the existing Flask app at
-- these tables until its data-access layer has been migrated and tested.
-- Roles are provisioned by trusted administrators, never from user metadata.
begin;

create table public.app_users (
  id uuid primary key references auth.users(id) on delete restrict,
  legacy_id bigint unique,
  username text not null unique,
  display_name text not null,
  role text not null check (role in ('student', 'mentor', 'placement_officer', 'admin')),
  cohort text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  check (role <> 'mentor' or (cohort is not null and length(trim(cohort)) > 0))
);

create table public.assessments (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  user_id uuid not null references public.app_users(id) on delete restrict,
  cohort text,
  profile_hash text not null,
  created_at timestamptz not null default now(),
  readiness_score integer not null,
  readiness_category text not null,
  model_probability double precision not null,
  calibrated_probability double precision,
  model_version text not null default 'unknown',
  student_json jsonb not null
);
create index assessments_user_created_idx on public.assessments(user_id, created_at desc);
create index assessments_cohort_idx on public.assessments(cohort);

create table public.coaching_records (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  student_id uuid not null references public.app_users(id) on delete restrict,
  author_id uuid not null references public.app_users(id) on delete restrict,
  kind text not null check (kind in ('goal', 'note', 'check_in', 'referral')),
  title text not null,
  detail text not null default '',
  due_date date,
  status text not null default 'open' check (status in ('open', 'in_progress', 'completed')),
  visibility text not null default 'student' check (visibility in ('student', 'mentor')),
  evidence_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index coaching_student_created_idx on public.coaching_records(student_id, created_at desc);

create table public.student_settings (
  student_id uuid primary key references public.app_users(id) on delete restrict,
  target_role text not null,
  target_roles jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now()
);

create table public.profile_evidence (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  student_id uuid not null references public.app_users(id) on delete restrict,
  evidence_type text not null check (evidence_type in ('project', 'internship', 'certification', 'portfolio', 'skill')),
  title text not null,
  detail text not null default '',
  evidence_url text,
  source text not null default 'self-reported',
  verification_status text not null default 'pending' check (verification_status in ('pending', 'verified', 'rejected')),
  submitted_at timestamptz not null default now(),
  verified_by uuid references public.app_users(id) on delete restrict,
  verified_at timestamptz
);
create index evidence_student_submitted_idx on public.profile_evidence(student_id, submitted_at desc);

create table public.profile_corrections (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  student_id uuid not null references public.app_users(id) on delete restrict,
  field_name text not null,
  current_value text not null default '',
  requested_value text not null default '',
  reason text not null default '',
  status text not null default 'open' check (status in ('open', 'reviewed', 'declined')),
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewer_id uuid references public.app_users(id) on delete restrict,
  resolution text not null default ''
);

create table public.placement_events (
  student_id uuid primary key references public.app_users(id) on delete restrict,
  stage text not null,
  company text not null default '',
  target_role text not null default '',
  updated_by uuid not null references public.app_users(id) on delete restrict,
  updated_at timestamptz not null default now()
);

create table public.staff_audit (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  actor_id uuid not null references public.app_users(id) on delete restrict,
  action text not null,
  subject_id uuid references public.app_users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table public.notifications (
  id bigint generated always as identity primary key,
  recipient_id uuid not null references public.app_users(id) on delete cascade,
  kind text not null,
  title text not null,
  message text not null,
  -- Internal relative path only; consumers must also validate before routing.
  link text check (link is null or (left(link, 1) = '/' and left(link, 2) <> '//')),
  event_key text,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  unique (recipient_id, event_key)
);
create index notifications_recipient_created_idx on public.notifications(recipient_id, created_at desc);

-- Notifications and coaching writes commit together. This only runs for the
-- future Postgres data layer; existing SQLite coaching writes do not trigger it.
create function public.notify_coaching_change() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' and new.visibility = 'student'
     and new.kind in ('goal', 'check_in') and new.author_id <> new.student_id
     and exists (select 1 from public.app_users u where u.id = new.student_id and u.is_active) then
    insert into public.notifications(recipient_id, kind, title, message, event_key)
      values (new.student_id, 'coaching_update', 'New mentor update',
              'A mentor added a student-visible update to your timeline.',
              'coaching-created:' || new.id::text)
      on conflict (recipient_id, event_key) do nothing;
  elsif tg_op = 'UPDATE' and old.status is distinct from new.status
        and new.status = 'completed' and new.kind = 'goal'
        and new.visibility = 'student' and new.author_id <> new.student_id
        and exists (
          select 1 from public.app_users author join public.app_users student on student.id = new.student_id
          where author.id = new.author_id and author.is_active and student.is_active
            and (author.role in ('admin', 'placement_officer')
                 or (author.role = 'mentor' and author.cohort = student.cohort))
        ) then
    insert into public.notifications(recipient_id, kind, title, message, event_key)
      values (new.author_id, 'goal_completed', 'Goal completed',
              'A student goal you created was marked complete. Review the timeline.',
              'goal-completed:' || new.id::text)
      on conflict (recipient_id, event_key) do nothing;
  end if;
  return new;
end;
$$;
revoke all on function public.notify_coaching_change() from public, anon, authenticated;
create trigger coaching_notifications after insert or update of status on public.coaching_records
  for each row execute function public.notify_coaching_change();

-- Deny by default. Only the user's own active profile and notifications are
-- directly exposed. Other data remains backend-only until per-role/cohort
-- policies and the migrated Flask data layer have been implemented and tested.
alter table public.app_users enable row level security;
alter table public.assessments enable row level security;
alter table public.coaching_records enable row level security;
alter table public.student_settings enable row level security;
alter table public.profile_evidence enable row level security;
alter table public.profile_corrections enable row level security;
alter table public.placement_events enable row level security;
alter table public.staff_audit enable row level security;
alter table public.notifications enable row level security;

revoke all on public.app_users, public.assessments, public.coaching_records,
  public.student_settings, public.profile_evidence, public.profile_corrections,
  public.placement_events, public.staff_audit, public.notifications from anon, authenticated;

grant select on public.app_users to authenticated;
create policy app_users_read_self on public.app_users for select to authenticated
  using (id = (select auth.uid()) and is_active);

grant select on public.notifications to authenticated;
grant update (read_at) on public.notifications to authenticated;
create policy notifications_read_self on public.notifications for select to authenticated
  using (recipient_id = (select auth.uid()) and exists (
    select 1 from public.app_users u where u.id = (select auth.uid()) and u.is_active
  ));
create policy notifications_update_self on public.notifications for update to authenticated
  using (recipient_id = (select auth.uid()) and exists (
    select 1 from public.app_users u where u.id = (select auth.uid()) and u.is_active
  ))
  with check (recipient_id = (select auth.uid()) and exists (
    select 1 from public.app_users u where u.id = (select auth.uid()) and u.is_active
  ));
commit;
