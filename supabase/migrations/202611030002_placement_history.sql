-- Staging schema for historical placement-stage events. The current Flask
-- application still uses SQLite; applying this migration does not move data.
begin;
create table public.placement_history (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  student_id uuid not null references public.app_users(id) on delete restrict,
  stage text not null,
  company text not null default '',
  target_role text not null default '',
  updated_by uuid not null references public.app_users(id) on delete restrict,
  updated_at timestamptz not null
);
create index placement_history_student_updated_idx on public.placement_history(student_id, updated_at desc);
alter table public.placement_history enable row level security;
revoke all on public.placement_history from public, anon, authenticated;
commit;
