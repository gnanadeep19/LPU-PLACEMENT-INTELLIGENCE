-- Staging storage for existing 5 MB study resources. Access remains backend-only
-- until the Postgres resource API and its role-scoped access checks are tested.
-- Creating this table does not copy any files or change the running app.
begin;
create table public.study_resources (
  id bigint generated by default as identity primary key,
  legacy_id bigint unique,
  student_id uuid not null references public.app_users(id) on delete restrict,
  author_id uuid not null references public.app_users(id) on delete restrict,
  title text not null,
  description text not null default '',
  filename text not null,
  category text not null default 'General',
  content bytea not null check (octet_length(content) between 1 and 5242880),
  created_at timestamptz not null
);
create index study_resources_student_created_idx on public.study_resources(student_id, created_at desc);
alter table public.study_resources enable row level security;
revoke all on public.study_resources from public, anon, authenticated;
commit;
